/// Gaps shorter than this are recorded (upper limit of the threshold slider).
const MAX_GAP_MS: f32 = 200.0;

#[derive(Clone, Copy)]
struct Ev {
    id: u32,
    down: bool,
    t: f64,
    clock: (u16, u16, u16),
}

static EVENTS: Mutex<Vec<Ev>> = Mutex::new(Vec::new());
static CTX: OnceLock<egui::Context> = OnceLock::new();
static START: OnceLock<Instant> = OnceLock::new();
static HOOK_FAILED: AtomicBool = AtomicBool::new(false);
/// Count software-generated (injected) key events too. Some keyboard software (remappers, vendor
/// utilities) re-sends every physical key as an injected event; the checkbox in the UI turns this on.
/// CHATTER_TEST_INJECTED=1 turns it on at startup (used for automated testing).
static COUNT_INJECTED: AtomicBool = AtomicBool::new(false);
/// Number of injected key events that were ignored.
static INJECTED_IGNORED: AtomicU64 = AtomicU64::new(0);

/// Key id: scan code | 0xE000 (extended key). Without a scan code: 0x10000 | virtual key code.
fn key_id(vk: u32, scan: u32, ext: bool) -> Option<u32> {
    // Fake Ctrl generated by AltGr.
    if scan & 0x200 != 0 {
        return None;
    }
    match vk {
        0xA1 => return Some(0x36),                         // Right Shift
        0xA0 => return if ext { None } else { Some(0x2A) }, // Left Shift (the extended one is a fake shift)
        _ => {}
    }
    if scan == 0 || scan > 0xFF {
        return Some(0x10000 | vk);
    }
    Some(scan | if ext { 0xE000 } else { 0 })
}

/// Same key ids for Raw Input, which reports a few keys differently from the hook.
fn raw_key_id(vk: u32, make: u32, flags: u32) -> Option<u32> {
    const RI_KEY_E0: u32 = 2;
    const RI_KEY_E1: u32 = 4;
    let ext = flags & RI_KEY_E0 != 0;
    match vk {
        0xFF => None,                            // part of a multi-code sequence
        0x13 => Some(0x45),                      // Pause (sent as E1 1D 45)
        0x90 => Some(0xE045),                    // Num Lock (the hook reports it as extended)
        _ if flags & RI_KEY_E1 != 0 => None,
        _ if ext && (make == 0x2A || make == 0x36) => None, // fake shifts around navigation keys
        _ if make == 0 || make > 0xFF => Some(0x10000 | vk),
        _ => Some(make | if ext { 0xE000 } else { 0 }),
    }
}

/// True if the foreground window belongs to this program.
fn we_are_foreground() -> bool {
    unsafe {
        let mut pid = 0u32;
        GetWindowThreadProcessId(GetForegroundWindow(), Some(&mut pid));
        pid == GetCurrentProcessId()
    }
}

fn record(id: Option<u32>, down: bool, injected: bool) {
    let t = START.get().map(|s| s.elapsed().as_secs_f64() * 1000.0).unwrap_or(0.0);
    if injected && !COUNT_INJECTED.load(Ordering::Relaxed) {
        if down {
            INJECTED_IGNORED.fetch_add(1, Ordering::Relaxed);
        }
    } else if let Some(id) = id {
        let st = unsafe { GetLocalTime() };
        if let Ok(mut v) = EVENTS.lock() {
            v.push(Ev { id, down, t, clock: (st.wHour, st.wMinute, st.wSecond) });
        }
    }
    if let Some(c) = CTX.get() {
        c.request_repaint();
    }
}

unsafe extern "system" fn hook(code: i32, w: WPARAM, l: LPARAM) -> LRESULT {
    if code == HC_ACTION as i32 && !we_are_foreground() {
        let k = &*(l.0 as *const KBDLLHOOKSTRUCT);
        let injected = k.flags.0 & LLKHF_INJECTED.0 != 0;
        let ext = k.flags.0 & LLKHF_EXTENDED.0 != 0;
        let msg = w.0 as u32;
        let down = msg == WM_KEYDOWN || msg == WM_SYSKEYDOWN;
        record(key_id(k.vkCode, k.scanCode, ext), down, injected);
    }
    CallNextHookEx(HHOOK::default(), code, w, l)
}

/// Receives Raw Input (WM_INPUT) for the keyboard; used only while our window is in the foreground.
unsafe extern "system" fn raw_wndproc(hwnd: HWND, msg: u32, w: WPARAM, l: LPARAM) -> LRESULT {
    if msg == WM_INPUT {
        let mut raw = RAWINPUT::default();
        let mut size = std::mem::size_of::<RAWINPUT>() as u32;
        let n = GetRawInputData(
            HRAWINPUT(l.0 as _),
            RID_INPUT,
            Some(&mut raw as *mut RAWINPUT as *mut _),
            &mut size,
            std::mem::size_of::<RAWINPUTHEADER>() as u32,
        );
        const RIM_TYPEKEYBOARD: u32 = 1;
        const RI_KEY_BREAK: u16 = 1;
        if n != u32::MAX && raw.header.dwType == RIM_TYPEKEYBOARD && we_are_foreground() {
            let kb = raw.data.keyboard;
            // Input sent by software has no device handle.
            let injected = raw.header.hDevice.is_invalid();
            let down = kb.Flags & RI_KEY_BREAK == 0;
            record(raw_key_id(kb.VKey as u32, kb.MakeCode as u32, kb.Flags as u32), down, injected);
        }
    }
    DefWindowProcW(hwnd, msg, w, l)
}

fn start_hook() {
    std::thread::spawn(|| unsafe {
        let hmod = GetModuleHandleW(None).unwrap_or_default();
        let hinst = HINSTANCE(hmod.0);
        if SetWindowsHookExW(WH_KEYBOARD_LL, Some(hook), hinst, 0).is_err() {
            HOOK_FAILED.store(true, Ordering::Relaxed);
        }
        // Raw Input: a message-only window on this thread. Registering the keyboard here replaces the
        // UI library's own keyboard registration, which it only uses for device events we don't need.
        let class = WNDCLASSW { lpfnWndProc: Some(raw_wndproc), hInstance: hinst, lpszClassName: w!("ChatterTestRawInput"), ..Default::default() };
        RegisterClassW(&class);
        if let Ok(hwnd) = CreateWindowExW(
            WINDOW_EX_STYLE(0),
            w!("ChatterTestRawInput"),
            w!(""),
            WINDOW_STYLE(0),
            0,
            0,
            0,
            0,
            HWND_MESSAGE,
            None,
            hinst,
            None,
        ) {
            let dev = RAWINPUTDEVICE { usUsagePage: 0x01, usUsage: 0x06, dwFlags: RIDEV_INPUTSINK, hwndTarget: hwnd };
            if RegisterRawInputDevices(&[dev], std::mem::size_of::<RAWINPUTDEVICE>() as u32).is_err() {
                HOOK_FAILED.store(true, Ordering::Relaxed);
            }
        } else {
            HOOK_FAILED.store(true, Ordering::Relaxed);
        }
        // The hook and the window are both served by this thread's message loop.
        let mut msg = MSG::default();
        while GetMessageW(&mut msg, HWND::default(), 0, 0).as_bool() {
            DispatchMessageW(&msg);
        }
    });
}

/// For testing: a layout loaded from CHATTER_TEST_LAYOUT (e.g. 00000407 for German) replaces the
/// current one, so other layouts can be checked without installing them.
static TEST_LAYOUT: OnceLock<usize> = OnceLock::new();

/// Keyboard layout of the foreground window (what the user is typing with right now).
fn current_layout() -> HKL {
    if let Some(h) = TEST_LAYOUT.get() {
        return HKL(*h as _);
    }
    unsafe {
        let tid = GetWindowThreadProcessId(GetForegroundWindow(), None);
        GetKeyboardLayout(tid)
    }
}

/// Physical keyboard shape. US-style layouts are usually on ANSI keyboards (no key next to left
/// Shift, one-row Enter); most European layouts are on ISO keyboards.
fn layout_is_ansi(hkl: HKL) -> bool {
    let lang = hkl.0 as usize as u32 & 0xFFFF;
    matches!(lang, 0x0409 | 0x1009 | 0x0404 | 0x0804 | 0x0C04 | 0x1004 | 0x0412 | 0x0411 | 0x0439 | 0x0421 | 0x0464)
}

/// True if the layout types characters with AltGr (Ctrl+Alt), so the right Alt key is labeled AltGr.
fn layout_has_altgr(hkl: HKL) -> bool {
    let mut state = [0u8; 256];
    for vk in [0x11, 0x12, 0xA2, 0xA5] {
        state[vk] = 0x80; // Ctrl, Alt, left Ctrl, right Alt
    }
    (0x30..=0xDFu32).any(|vk| {
        let mut buf = [0u16; 8];
        // Flag 4: don't change the keyboard state (dead keys).
        let n = unsafe { ToUnicodeEx(vk, 0, &state, &mut buf, 4, hkl) };
        n < 0 || (n > 0 && buf[0] >= 0x20)
    })
}

/// The character a key types in the given layout (unshifted, shown in upper case), if any.
fn key_char(id: u32, hkl: HKL) -> Option<String> {
    if id & 0xE000 != 0 {
        return None;
    }
    let scan = id & 0xFF;
    unsafe {
        // Numpad decimal key: comma or period depending on the layout.
        let vk = if scan == 0x53 { 0x6E } else { MapVirtualKeyExW(scan, MAPVK_VSC_TO_VK_EX, hkl) };
        if vk == 0 {
            return None;
        }
        // Dead keys (accents) have the top bit set.
        let c = char::from_u32(MapVirtualKeyExW(vk, MAPVK_VK_TO_CHAR, hkl) & 0xFFFF)?;
        if c <= ' ' {
            return None;
        }
        // Turkish: the upper case of "i" is "İ". Keep "ß" (its upper case is "SS").
        if c == 'i' {
            return Some("İ".into());
        }
        let up: String = c.to_uppercase().collect();
        Some(if up.chars().count() == 1 { up } else { c.to_string() })
    }
}

fn key_name(id: u32, hkl: HKL) -> String {
    if id & 0x10000 != 0 {
        return format!("Key (VK {:#04X})", id & 0xFF);
    }
    // Windows has no names for F13–F24.
    match id {
        0x64..=0x6E => return format!("F{}", id - 0x64 + 13),
        0x76 => return "F24".into(),
        _ => {}
    }
    if let Some(c) = key_char(id, hkl) {
        return c;
    }
    let lp = ((id & 0xFF) << 16) | if id & 0xE000 != 0 { 1 << 24 } else { 0 };
    let mut buf = [0u16; 64];
    let n = unsafe { GetKeyNameTextW(lp as i32, &mut buf) };
    if n > 0 {
        String::from_utf16_lossy(&buf[..n as usize])
    } else {
        format!("Key {:#06X}", id)
    }
}

/// A key on the on-screen keyboard (position and size in key units).
struct K {
    id: u32,
    x: f32,
    y: f32,
    w: f32,
    h: f32,
    label: &'static str,
}

/// Full-size ANSI or ISO keyboard. Character labels come from the active Windows keyboard layout.
fn layout(iso: bool, altgr: bool) -> Vec<K> {
    let mut v = Vec::new();
    let mut add = |id: u32, x: f32, y: f32, w: f32, h: f32, label: &'static str| v.push(K { id, x, y, w, h, label });
    const F: [&str; 12] = ["F1", "F2", "F3", "F4", "F5", "F6", "F7", "F8", "F9", "F10", "F11", "F12"];
    const F_SCAN: [u32; 12] = [0x3B, 0x3C, 0x3D, 0x3E, 0x3F, 0x40, 0x41, 0x42, 0x43, 0x44, 0x57, 0x58];
    add(0x01, 0.0, 0.0, 1.0, 1.0, "Esc");
    for i in 0..12 {
        let x = 2.0 + i as f32 + (i / 4) as f32 * 0.5;
        add(F_SCAN[i], x, 0.0, 1.0, 1.0, F[i]);
    }
    add(0xE037, 15.25, 0.0, 1.0, 1.0, "PrtSc");
    add(0x46, 16.25, 0.0, 1.0, 1.0, "ScrLk");
    add(0x45, 17.25, 0.0, 1.0, 1.0, "Pause");
    // Number row
    add(0x29, 0.0, 1.5, 1.0, 1.0, "");
    for i in 0..12 {
        add(0x02 + i, 1.0 + i as f32, 1.5, 1.0, 1.0, "");
    }
    add(0x0E, 13.0, 1.5, 2.0, 1.0, "Backspace");
    // Top letter row
    add(0x0F, 0.0, 2.5, 1.5, 1.0, "Tab");
    for i in 0..12 {
        add(0x10 + i, 1.5 + i as f32, 2.5, 1.0, 1.0, "");
    }
    if iso {
        add(0x1C, 13.75, 2.5, 1.25, 2.0, "Enter");
    } else {
        add(0x2B, 13.5, 2.5, 1.5, 1.0, "");
    }
    // Home row
    add(0x3A, 0.0, 3.5, 1.75, 1.0, "Caps");
    for i in 0..11 {
        add(0x1E + i, 1.75 + i as f32, 3.5, 1.0, 1.0, "");
    }
    if iso {
        add(0x2B, 12.75, 3.5, 1.0, 1.0, "");
    } else {
        add(0x1C, 12.75, 3.5, 2.25, 1.0, "Enter");
    }
    // Bottom letter row
    if iso {
        add(0x2A, 0.0, 4.5, 1.25, 1.0, "Shift");
        add(0x56, 1.25, 4.5, 1.0, 1.0, "");
    } else {
        add(0x2A, 0.0, 4.5, 2.25, 1.0, "Shift");
    }
    for i in 0..10 {
        add(0x2C + i, 2.25 + i as f32, 4.5, 1.0, 1.0, "");
    }
    add(0x36, 12.25, 4.5, 2.75, 1.0, "Shift");
    // Bottom row
    let mut x = 0.0;
    for (id, w, l) in [
        (0x1D, 1.25, "Ctrl"),
        (0xE05B, 1.25, "Win"),
        (0x38, 1.25, "Alt"),
        (0x39, 6.25, "Space"),
        (0xE038, 1.25, if altgr { "AltGr" } else { "Alt" }),
        (0xE05C, 1.25, "Win"),
        (0xE05D, 1.25, "Menu"),
        (0xE01D, 1.25, "Ctrl"),
    ] {
        add(id, x, 5.5, w, 1.0, l);
        x += w;
    }
    // Navigation cluster
    add(0xE052, 15.25, 1.5, 1.0, 1.0, "Ins");
    add(0xE047, 16.25, 1.5, 1.0, 1.0, "Home");
    add(0xE049, 17.25, 1.5, 1.0, 1.0, "PgUp");
    add(0xE053, 15.25, 2.5, 1.0, 1.0, "Del");
    add(0xE04F, 16.25, 2.5, 1.0, 1.0, "End");
    add(0xE051, 17.25, 2.5, 1.0, 1.0, "PgDn");
    add(0xE048, 16.25, 4.5, 1.0, 1.0, "@0");
    add(0xE04B, 15.25, 5.5, 1.0, 1.0, "@1");
    add(0xE050, 16.25, 5.5, 1.0, 1.0, "@2");
    add(0xE04D, 17.25, 5.5, 1.0, 1.0, "@3");
    // Numpad
    let n = 18.5;
    add(0xE045, n, 1.5, 1.0, 1.0, "Num");
    add(0xE035, n + 1.0, 1.5, 1.0, 1.0, "/");
    add(0x37, n + 2.0, 1.5, 1.0, 1.0, "*");
    add(0x4A, n + 3.0, 1.5, 1.0, 1.0, "-");
    add(0x47, n, 2.5, 1.0, 1.0, "7");
    add(0x48, n + 1.0, 2.5, 1.0, 1.0, "8");
    add(0x49, n + 2.0, 2.5, 1.0, 1.0, "9");
    add(0x4E, n + 3.0, 2.5, 1.0, 2.0, "+");
    add(0x4B, n, 3.5, 1.0, 1.0, "4");
    add(0x4C, n + 1.0, 3.5, 1.0, 1.0, "5");
    add(0x4D, n + 2.0, 3.5, 1.0, 1.0, "6");
    add(0x4F, n, 4.5, 1.0, 1.0, "1");
    add(0x50, n + 1.0, 4.5, 1.0, 1.0, "2");
    add(0x51, n + 2.0, 4.5, 1.0, 1.0, "3");
    add(0xE01C, n + 3.0, 4.5, 1.0, 2.0, "Enter");
    add(0x52, n, 5.5, 2.0, 1.0, "0");
    add(0x53, n + 2.0, 5.5, 1.0, 1.0, "");
    v
}

#[derive(Default)]
struct Stat {
    presses: u32,
    repeats: u32,
    down: bool,
    last_down: f64,
    last_up: Option<f64>,
    last_hold: f32,
    /// Short release-to-press gaps (ms, below MAX_GAP_MS).
    gaps: Vec<f32>,
}

impl Stat {
    fn chatter(&self, thr: f32) -> usize {
        self.gaps.iter().filter(|g| **g < thr).count()
    }
    fn min_gap(&self) -> Option<f32> {
        self.gaps.iter().copied().reduce(f32::min)
    }
}

struct Bounce {
    id: u32,
    gap: f32,
    hold: f32,
    clock: (u16, u16, u16),
}

struct App {
    stats: HashMap<u32, Stat>,
    bounces: Vec<Bounce>,
    names: HashMap<u32, String>,
    keys: Vec<K>,
    thr: f32,
    /// Typing area for testing inside the app.
    text: String,
    /// Keyboard layout the labels were made for.
    hkl: HKL,
    shape: Shape,
    /// The key next to left Shift (ISO only) was pressed, so the keyboard is ISO.
    saw_iso_key: bool,
    iso: bool,
}

#[derive(Clone, Copy, PartialEq)]
enum Shape {
    Auto,
    Ansi,
    Iso,
}

const UNTESTED: Color32 = Color32::from_rgb(52, 56, 64);
const OK: Color32 = Color32::from_rgb(40, 120, 70);
const WARN: Color32 = Color32::from_rgb(214, 128, 20);
const BAD: Color32 = Color32::from_rgb(196, 40, 48);

impl App {
    fn new() -> Self {
        let mut app = App {
            stats: HashMap::new(),
            bounces: Vec::new(),
            names: HashMap::new(),
            keys: Vec::new(),
            thr: 50.0,
            text: String::new(),
            hkl: HKL::default(),
            shape: Shape::Auto,
            saw_iso_key: false,
            iso: true,
        };
        app.refresh_layout(true);
        app
    }

    /// Follows the keyboard layout the user is typing with (labels, ANSI/ISO shape, AltGr).
    fn refresh_layout(&mut self, force: bool) {
        let hkl = current_layout();
        let hkl = if hkl.is_invalid() { self.hkl } else { hkl };
        let iso = match self.shape {
            Shape::Ansi => false,
            Shape::Iso => true,
            Shape::Auto => self.saw_iso_key || !layout_is_ansi(hkl),
        };
        if force || hkl != self.hkl || iso != self.iso {
            self.hkl = hkl;
            self.iso = iso;
            self.names.clear();
            self.keys = layout(iso, layout_has_altgr(hkl));
        }
    }

    fn name(&mut self, id: u32) -> String {
        let hkl = self.hkl;
        self.names.entry(id).or_insert_with(|| key_name(id, hkl)).clone()
    }

    fn poll(&mut self) {
        let evs = std::mem::take(&mut *EVENTS.lock().unwrap());
        for e in evs {
            if e.id == 0x56 {
                self.saw_iso_key = true;
            }
            let s = self.stats.entry(e.id).or_default();
            if e.down {
                if s.down {
                    s.repeats += 1; // auto-repeat while held
                    continue;
                }
                s.down = true;
                s.presses += 1;
                if let Some(up) = s.last_up {
                    let gap = (e.t - up) as f32;
                    if gap < MAX_GAP_MS {
                        s.gaps.push(gap);
                        self.bounces.push(Bounce { id: e.id, gap, hold: s.last_hold, clock: e.clock });
                    }
                }
                s.last_down = e.t;
            } else if s.down {
                s.down = false;
                s.last_up = Some(e.t);
                s.last_hold = (e.t - s.last_down) as f32;
            }
        }
    }

    fn color(&self, s: Option<&Stat>) -> Color32 {
        match s {
            None => UNTESTED,
            Some(s) if s.presses == 0 => UNTESTED,
            Some(s) => match s.chatter(self.thr) {
                0 => OK,
                1 => WARN,
                _ => BAD,
            },
        }
    }

    fn keyboard_ui(&mut self, ui: &mut egui::Ui) {
        let u = (ui.available_width() / 22.5).clamp(22.0, 46.0);
        let (resp, painter) = ui.allocate_painter(vec2(22.5 * u, 6.5 * u), Sense::hover());
        let o = resp.rect.min;
        let mut hover: Option<u32> = None;
        for k in &self.keys {
            let r = Rect::from_min_size(pos2(o.x + k.x * u, o.y + k.y * u), vec2(k.w * u, k.h * u)).shrink(2.0);
            let s = self.stats.get(&k.id);
            painter.rect_filled(r, 4.0, self.color(s));
            if s.is_some_and(|s| s.down) {
                painter.rect_stroke(r, 4.0, Stroke::new(2.5, Color32::from_rgb(253, 224, 71)), StrokeKind::Inside);
            }
            let label = if k.label.is_empty() {
                let hkl = self.hkl;
                self.names.entry(k.id).or_insert_with(|| key_name(k.id, hkl)).clone()
            } else {
                k.label.to_string()
            };
            if let Some(dir) = label.strip_prefix('@') {
                // Arrow keys: the font has no arrow glyphs, so draw triangles.
                let c = r.center();
                let a = u * 0.16;
                let pts = match dir {
                    "0" => vec![c + vec2(0.0, -a), c + vec2(a, a * 0.7), c + vec2(-a, a * 0.7)],
                    "1" => vec![c + vec2(-a, 0.0), c + vec2(a * 0.7, -a), c + vec2(a * 0.7, a)],
                    "2" => vec![c + vec2(0.0, a), c + vec2(-a, -a * 0.7), c + vec2(a, -a * 0.7)],
                    _ => vec![c + vec2(a, 0.0), c + vec2(-a * 0.7, a), c + vec2(-a * 0.7, -a)],
                };
                painter.add(egui::Shape::convex_polygon(pts, Color32::WHITE, Stroke::NONE));
            } else {
                let size = if label.chars().count() <= 2 { u * 0.36 } else { u * 0.24 };
                painter.text(r.center() - vec2(0.0, u * 0.06), Align2::CENTER_CENTER, label, FontId::proportional(size), Color32::WHITE);
            }
            if let Some(n) = s.map(|s| s.chatter(self.thr)).filter(|n| *n > 0) {
                painter.text(r.right_bottom() - vec2(3.0, 1.0), Align2::RIGHT_BOTTOM, format!("×{n}"), FontId::proportional(u * 0.24), Color32::WHITE);
            }
            if resp.hovered() && ui.ctx().pointer_hover_pos().is_some_and(|p| r.contains(p)) {
                hover = Some(k.id);
            }
        }
        if let Some(id) = hover {
            let name = self.name(id);
            let text = match self.stats.get(&id) {
                Some(s) if s.presses > 0 => {
                    let mut t = format!("{name}\nPresses: {}\nChatter: {}", s.presses, s.chatter(self.thr));
                    if let Some(g) = s.min_gap() {
                        t += &format!("\nShortest release-to-press gap: {g:.0} ms");
                    }
                    t
                }
                _ => format!("{name}\nNot pressed yet"),
            };
            resp.on_hover_text(text);
        }
    }

    fn summary_text(&mut self) -> String {
        let mut rows: Vec<(u32, u32, usize, Option<f32>)> =
            self.stats.iter().filter(|(_, s)| s.presses > 0).map(|(id, s)| (*id, s.presses, s.chatter(self.thr), s.min_gap())).collect();
        rows.sort_by(|a, b| b.2.cmp(&a.2).then(b.1.cmp(&a.1)));
        let mut out = format!("Keyboard chatter test (threshold {:.0} ms)\nKey\tPresses\tChatter\tShortest gap (ms)\n", self.thr);
        for (id, p, c, g) in rows {
            let name = self.name(id);
            out += &format!("{name}\t{p}\t{c}\t{}\n", g.map(|g| format!("{g:.0}")).unwrap_or_else(|| "-".into()));
        }
        out
    }
}

impl eframe::App for App {
    fn logic(&mut self, ctx: &egui::Context, _frame: &mut eframe::Frame) {
        self.poll();
        self.refresh_layout(false);
        // Notice layout switches (e.g. Win+Space) even when no other event arrives.
        ctx.request_repaint_after(std::time::Duration::from_secs(1));
    }

    fn ui(&mut self, ui: &mut egui::Ui, _frame: &mut eframe::Frame) {
        egui::CentralPanel::default()
            .frame(egui::Frame::new().fill(Color32::from_rgb(24, 26, 31)).inner_margin(egui::Margin::same(16)))
            .show(ui, |ui| {
                egui::ScrollArea::vertical().auto_shrink(false).show(ui, |ui| self.main_ui(ui));
            });
    }
}

impl App {
    fn main_ui(&mut self, ui: &mut egui::Ui) {
        ui.heading(RichText::new("Keyboard Chatter Test").size(24.0).strong());
        ui.add_space(4.0);
        ui.label(
            "Press each key 10–20 times at a normal pace (release it fully each time). If a key is pressed again \
             sooner than the threshold after being released, it counts as chatter. Auto-repeat while holding a key is not counted. \
             Keys are detected system-wide, so you can type in the box below or in any other program.",
        );
        if HOOK_FAILED.load(Ordering::Relaxed) {
            ui.colored_label(BAD, "Could not listen to the keyboard (failed to install the hook).");
        }
        ui.add_space(8.0);
        ui.horizontal(|ui| {
            ui.label("Threshold:");
            ui.add(egui::Slider::new(&mut self.thr, 10.0..=150.0).step_by(5.0).suffix(" ms"));
            ui.add_space(12.0);
            if ui.button("Reset").clicked() {
                self.stats.clear();
                self.bounces.clear();
            }
            if ui.button("Copy results").clicked() {
                let t = self.summary_text();
                ui.ctx().copy_text(t);
            }
            ui.add_space(12.0);
            ui.label("Keyboard shape:");
            let auto = format!("Auto ({})", if self.iso { "ISO" } else { "ANSI" });
            let before = self.shape;
            egui::ComboBox::from_id_salt("shape")
                .selected_text(match self.shape {
                    Shape::Auto => auto.clone(),
                    Shape::Ansi => "ANSI".into(),
                    Shape::Iso => "ISO".into(),
                })
                .show_ui(ui, |ui| {
                    ui.selectable_value(&mut self.shape, Shape::Auto, auto);
                    ui.selectable_value(&mut self.shape, Shape::Ansi, "ANSI (one-row Enter)");
                    ui.selectable_value(&mut self.shape, Shape::Iso, "ISO (two-row Enter)");
                });
            if self.shape != before {
                self.refresh_layout(true);
            }
        });
        ui.label(
            RichText::new("Real chatter is usually under 30 ms; a deliberate double tap of the same key rarely takes less than 80–100 ms.")
                .small()
                .weak(),
        );
        let mut count_injected = COUNT_INJECTED.load(Ordering::Relaxed);
        let ignored = INJECTED_IGNORED.load(Ordering::Relaxed);
        ui.horizontal(|ui| {
            if ui
                .checkbox(&mut count_injected, "Count software-generated keys")
                .on_hover_text(
                    "Some keyboard software (key remappers, vendor utilities) re-sends every key you press. \
                     Turn this on if your key presses are not being counted.",
                )
                .changed()
            {
                COUNT_INJECTED.store(count_injected, Ordering::Relaxed);
            }
            if !count_injected && ignored > 0 {
                ui.label(
                    RichText::new(format!("{ignored} software-generated key presses ignored. If these are your own presses, turn this on."))
                        .color(WARN),
                );
            }
        });
        ui.add_space(6.0);

        let tested = self.stats.values().filter(|s| s.presses > 0).count();
        let total: u32 = self.stats.values().map(|s| s.presses).sum();
        let bad = self.stats.values().filter(|s| s.chatter(self.thr) > 0).count();
        ui.horizontal(|ui| {
            ui.label(format!("Keys tested: {tested}   ·   Total presses: {total}   ·   "));
            ui.label(RichText::new(format!("Chattering keys: {bad}")).strong().color(if bad > 0 { WARN } else { Color32::LIGHT_GREEN }));
        });
        ui.add_space(8.0);

        self.keyboard_ui(ui);
        ui.add_space(6.0);
        ui.horizontal(|ui| {
            for (c, t) in [(UNTESTED, "Not pressed"), (OK, "OK"), (WARN, "1 chatter"), (BAD, "2+ chatters")] {
                let (r, _) = ui.allocate_exact_size(vec2(14.0, 14.0), Sense::hover());
                ui.painter().rect_filled(r, 3.0, c);
                ui.label(t);
                ui.add_space(10.0);
            }
            let (r, _) = ui.allocate_exact_size(vec2(14.0, 14.0), Sense::hover());
            ui.painter().rect_stroke(r, 3.0, Stroke::new(2.0, Color32::from_rgb(253, 224, 71)), StrokeKind::Inside);
            ui.label("Held down");
        });
        ui.add_space(12.0);

        ui.horizontal(|ui| {
            ui.label(RichText::new("Typing test").size(17.0).strong());
            if ui.small_button("Clear").clicked() {
                self.text.clear();
            }
        });
        ui.add_space(4.0);
        ui.add(
            egui::TextEdit::multiline(&mut self.text)
                .hint_text("Type here to test your keyboard, e.g. \"the quick brown fox jumps over the lazy dog\"…")
                .desired_rows(4)
                .desired_width(f32::INFINITY)
                .font(FontId::proportional(18.0)),
        );
        ui.label(
            RichText::new("If a chatter blocker is running, doubled letters may be filtered out of this box, but they are still counted above.")
                .small()
                .weak(),
        );
        ui.add_space(12.0);

        let thr = self.thr;
        let mut rows: Vec<(u32, u32, usize, Option<f32>)> =
            self.stats.iter().filter(|(_, s)| s.chatter(thr) > 0).map(|(id, s)| (*id, s.presses, s.chatter(thr), s.min_gap())).collect();
        rows.sort_by(|a, b| b.2.cmp(&a.2).then(b.1.cmp(&a.1)));
        let log: Vec<(String, f32, f32, (u16, u16, u16))> = {
            let items: Vec<(u32, f32, f32, (u16, u16, u16))> =
                self.bounces.iter().rev().filter(|b| b.gap < thr).take(100).map(|b| (b.id, b.gap, b.hold, b.clock)).collect();
            items.into_iter().map(|(id, g, h, c)| (self.name(id), g, h, c)).collect()
        };
        let names: Vec<String> = rows.iter().map(|r| self.name(r.0)).collect();

        ui.columns(2, |cols| {
            let ui = &mut cols[0];
            ui.label(RichText::new("Chattering keys").size(17.0).strong());
            ui.add_space(4.0);
            if rows.is_empty() {
                ui.label(RichText::new("No chatter detected yet.").weak());
            } else {
                egui::Grid::new("table").striped(true).spacing(vec2(18.0, 6.0)).show(ui, |ui| {
                    ui.strong("Key");
                    ui.strong("Presses");
                    ui.strong("Chatter");
                    ui.strong("Rate");
                    ui.strong("Shortest gap");
                    ui.end_row();
                    for (r, name) in rows.iter().zip(&names) {
                        let rate = r.2 as f32 / r.1.max(1) as f32 * 100.0;
                        ui.label(RichText::new(name).strong());
                        ui.label(r.1.to_string());
                        ui.label(RichText::new(r.2.to_string()).color(if r.2 > 1 { BAD } else { WARN }).strong());
                        ui.label(format!("{rate:.0}%"));
                        ui.label(r.3.map(|g| format!("{g:.0} ms")).unwrap_or_default());
                        ui.end_row();
                    }
                });
            }

            let ui = &mut cols[1];
            ui.label(RichText::new("Recent chatter").size(17.0).strong());
            ui.add_space(4.0);
            if log.is_empty() {
                ui.label(RichText::new("—").weak());
            }
            for (name, gap, hold, (h, m, s)) in &log {
                ui.label(format!("{h:02}:{m:02}:{s:02}   {name}: held {hold:.0} ms, pressed again {gap:.0} ms after release"));
            }
        });
    }
}

fn main() -> eframe::Result {
    START.get_or_init(Instant::now);
    COUNT_INJECTED.store(std::env::var_os("CHATTER_TEST_INJECTED").is_some(), Ordering::Relaxed);
    let options = eframe::NativeOptions {
        viewport: egui::ViewportBuilder::default()
            .with_title("Keyboard Chatter Test")
            .with_inner_size([1120.0, 820.0])
            .with_min_inner_size([640.0, 480.0]),
        ..Default::default()
    };
    // Test layout: loaded without telling the shell, unloaded on exit unless it was already installed.
    let mut unload: Option<HKL> = None;
    if let Ok(klid) = std::env::var("CHATTER_TEST_LAYOUT") {
        unsafe {
            let mut list = [HKL::default(); 64];
            let n = GetKeyboardLayoutList(Some(&mut list)) as usize;
            if let Ok(h) = LoadKeyboardLayoutW(&windows::core::HSTRING::from(klid), KLF_NOTELLSHELL) {
                if !list[..n].contains(&h) {
                    unload = Some(h);
                }
                let _ = TEST_LAYOUT.set(h.0 as usize);
            }
        }
    }
    let result = eframe::run_native(
        "Keyboard Chatter Test",
        options,
        Box::new(|cc| {
            let _ = CTX.set(cc.egui_ctx.clone());
            start_hook();
            Ok(Box::new(App::new()))
        }),
    );
    if let Some(h) = unload {
        unsafe {
            let _ = UnloadKeyboardLayout(h);
        }
    }
    result
}
