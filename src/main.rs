//! Keyboard chatter test: finds keys that register two presses for a single physical press.
//!
//! Key events come from two sources, never both for the same key press:
//! - A low-level keyboard hook (WH_KEYBOARD_LL) while another program is in the foreground. It is
//!   installed after any chatter blocker that is already running, so it sees key presses before
//!   the blocker can drop them.
//! - Raw Input while this program's own window is in the foreground. Windows does not call
//!   low-level hooks then (observed on Windows 11), so chatter blockers do not run either.
//!
//! Events are never modified or blocked. If a key is pressed again sooner than the threshold after
//! it was released, that counts as chatter. Auto-repeat while a key is held (key-down without a
//! key-up in between) is not counted. Software-generated (injected) key events are ignored unless
//! the user turns them on.

